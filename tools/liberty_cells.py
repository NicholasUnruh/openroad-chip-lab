"""Write zero-delay Verilog models of standard cells from their Liberty logic functions.

Combinational outputs become continuous assignments of the Liberty `function`; edge-triggered
cells (`ff` groups) become one always block, with any asynchronous clear and preset. The models
exist so routed netlists can be simulated for switching activity (tools/ppa_power.sh,
tools/tile_power.sh); they carry no timing.

usage: python3 tools/liberty_cells.py <out.v> <cell.lib[.gz]>...
"""

import gzip
import re
import sys


def read(path):
    opener = gzip.open if path.endswith(".gz") else open
    with opener(path, "rt") as handle:
        return handle.read()


def groups(text, kind):
    """Yield (name, body) for each top-level `kind (name) { ... }` group in text."""
    for match in re.finditer(r"\b" + kind + r"\s*\(([^)]*)\)\s*\{", text):
        depth, start = 1, match.end()
        pos = start
        while depth and pos < len(text):
            depth += {"{": 1, "}": -1}.get(text[pos], 0)
            pos += 1
        yield match.group(1).strip().strip('"'), text[start : pos - 1]


def attribute(body, name):
    match = re.search(r"\b" + name + r'\s*:\s*"?([^";]*)"?\s*;', body)
    return match.group(1).strip() if match else None


def verilog_expr(function):
    """Liberty boolean syntax (* + ! ^ ' and juxtaposition) to Verilog."""
    expr = re.sub(r"([A-Za-z_]\w*)'", r"(!\1)", function)
    expr = re.sub(r"(\w|\))\s+(?=[A-Za-z_(!])", r"\1 * ", expr.strip())
    return expr.replace("!", "~").replace("*", "&").replace("+", "|")


def cell_model(name, body):
    # A scan cell's test_cell group repeats its pins and ff for DFT tools; model the cell once.
    for _, test_body in groups(body, "test_cell"):
        body = body.replace(test_body, "")
    pins = []
    for pin, pin_body in groups(body, "pin"):
        pins.append(
            (pin, attribute(pin_body, "direction"), attribute(pin_body, "function"))
        )
    lines = [f"module {name} (" + ", ".join(p for p, _, _ in pins) + ");"]
    for pin, direction, _ in pins:
        lines.append(f"    {direction} {pin};")
    for state, ff_body in groups(body, "ff"):
        names = [s.strip().strip('"') for s in state.split(",")]
        clock, next_state = (
            attribute(ff_body, "clocked_on"),
            attribute(ff_body, "next_state"),
        )
        q = names[0]
        edge = "negedge" if clock.startswith("!") else "posedge"
        events = [f"{edge} {clock.lstrip('!')}"]
        # Asynchronous clear and preset (SKY130 "!RESET_B", "!SET_B"); with both active the
        # state takes clear_preset_var1.
        conditions = []
        for kind, value in (("clear", "1'b0"), ("preset", "1'b1")):
            pin = attribute(ff_body, kind)
            if pin:
                events.append(("negedge " if pin.startswith("!") else "posedge ") + pin.lstrip("!"))
                conditions.append((verilog_expr(pin), value))
        both = attribute(ff_body, "clear_preset_var1")
        if len(conditions) == 2 and both:
            conditions.insert(
                0,
                (f"({conditions[0][0]}) & ({conditions[1][0]})", "1'b1" if both == "H" else "1'b0"),
            )
        lines.append(f"    reg {q} = 1'b0;")
        lines.append(f"    wire {names[1]} = ~{q};")
        update = "".join(f"if ({c}) {q} <= {v}; else " for c, v in conditions)
        lines.append(
            f"    always @({' or '.join(events)}) {update}{q} <= {verilog_expr(next_state)};"
        )
    if re.search(r"\blatch\s*\(", body) or any(
        d not in ("input", "output") for _, d, _ in pins
    ):
        raise ValueError(f"{name}: latch and clock-gating cells are not modelled")
    for pin, direction, function in pins:
        if direction == "output" and function:
            lines.append(f"    assign {pin} = {verilog_expr(function)};")
    lines.append("endmodule")
    return "\n".join(lines)


def main(argv):
    if len(argv) < 3 or argv[1] == "--help":
        print(__doc__)
        return 0 if argv[1:2] == ["--help"] else 2
    models, skipped = [], []
    for path in argv[2:]:
        for name, body in groups(read(path), "cell"):
            try:
                models.append(cell_model(name, body))
            except ValueError as error:
                skipped.append(str(error))
    with open(argv[1], "w") as out:
        out.write("// Generated by tools/liberty_cells.py; zero-delay logic only.\n")
        out.write("\n".join(models) + "\n")
    print(
        f"wrote {argv[1]}: {len(models)} cells; skipped {len(skipped)} latch and clock-gating cells"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
