"""Write a stimulus testbench for a PPA harness from realistic quantized operand streams.

Each clock carries independent N(0, 1) operands quantized to the harness format (OCP MX blocks
share a power-of-two scale); the accumulator input carries N(0, 16) FP32 values. The testbench
drives the harness at 1 GHz, dumps a VCD of it after a pipeline warm-up, and logs every output
so gate-level and RTL simulations can be compared (tools/ppa_power.sh).

usage: python3 tools/ppa_activity.py <harness> <out_dir> [clocks]
"""

import math
import random
import struct
import sys


def fp32_bits(x):
    return struct.unpack("<I", struct.pack("<f", x))[0]


def bf16(x):
    raw = fp32_bits(x)
    return ((raw + 0x7FFF + ((raw >> 16) & 1)) >> 16) & 0xFFFF


def small_float(x, exp_bits, man_bits, max_value):
    """Nearest-even encoding of x in a small sign/exponent/mantissa format, saturating."""
    sign = 1 if x < 0 else 0
    x = min(abs(x), max_value)
    bias = (1 << (exp_bits - 1)) - 1
    if x == 0:
        return sign << (exp_bits + man_bits)
    exponent = max(math.floor(math.log2(x)), 1 - bias)
    step = 2.0 ** (exponent - man_bits)
    q = round(x / step) * step
    if q >= 2.0 ** (exponent + 1):
        exponent += 1
    q = min(q, max_value)
    field = exponent + bias if q >= 2.0 ** (1 - bias) else 0
    frac = round(q / 2.0 ** ((field if field else 1) - bias - man_bits)) - (
        1 << man_bits if field else 0
    )
    return sign << (exp_bits + man_bits) | field << man_bits | int(frac)


FORMATS = {
    "bf16": (16, lambda x: bf16(x)),
    "e4m3": (8, lambda x: small_float(x, 4, 3, 448.0)),
    "e5m2": (8, lambda x: small_float(x, 5, 2, 57344.0)),
    "e2m1": (4, lambda x: small_float(x, 2, 1, 6.0)),
    "int8": (8, lambda x: max(-127, min(127, round(x * 32))) & 0xFF),
}
# Harness: element format, elements per operand, MX block (shared scale) or not, extra ports.
HARNESSES = {
    "ppa_fma_bf16": ("bf16", 1, False),
    "ppa_dot8_bf16": ("bf16", 8, False),
    **{f"ppa_dot8_bf16_f{frame}": ("bf16", 8, False) for frame in (24, 28, 36, 40)},
    "ppa_dot8_e4m3": ("e4m3", 8, False),
    "ppa_dot8_e5m2": ("e5m2", 8, False),
    "ppa_dot8_int8": ("int8", 8, False),
    "ppa_dot32_mxfp8": ("e4m3", 32, True),
    "ppa_dot32_mxfp4": ("e2m1", 32, True),
}
EMAX = {"e4m3": 8, "e2m1": 2}  # largest element exponent, per OCP MX scale selection


def operand(rng, fmt, count, mx):
    width, encode = FORMATS[fmt]
    values = [rng.gauss(0, 1) for _ in range(count)]
    scale = 0
    if mx:
        peak = max(abs(v) for v in values) or 1.0
        shared = math.floor(math.log2(peak)) - EMAX[fmt]
        scale = shared + 127
        values = [v / 2.0**shared for v in values]
    word = 0
    for k, v in enumerate(values):
        word |= encode(v) << (width * k)
    return word, width * count, scale


WARMUP = 16  # clocks before the VCD starts; fills the deepest (eight-clock) pipeline


def testbench(harness, out_dir, clocks, total, ports, outputs):
    connections = []
    low = total
    for name, (width, _) in ports.items():
        low -= width
        connections.append(f".{name}(stimulus[{low + width - 1}:{low}])")
    connections += [f".{name}({name})" for name in outputs]
    wires = "\n".join(
        f"    wire [{width - 1}:0] {name};" for name, width in outputs.items()
    )
    return f"""`timescale 1ps/1ps
// Generated by tools/ppa_activity.py {harness}: {clocks} clocks at 1 GHz.
module ppa_tb;
    reg clk = 1'b0;
    reg [{total - 1}:0] memory [0:{clocks - 1}];
    reg [{total - 1}:0] stimulus;
{wires}
    {harness} dut (.clk(clk), {", ".join(connections)});
    integer i, log;
    initial begin
        $readmemh("{out_dir}/stimulus.hex", memory);
        log = $fopen("{out_dir}/outputs.txt");
        stimulus = memory[0];
        for (i = 0; i < {clocks}; i = i + 1) begin
            if (i == {WARMUP}) begin
                $dumpfile("{out_dir}/activity.vcd");
                $dumpvars(0, dut);
            end
            #500 clk = 1'b1;
            #1 stimulus = memory[(i + 1) % {clocks}];
            #499 clk = 1'b0;
            $fdisplay(log, "{" ".join("%h" for _ in outputs)}", {", ".join(outputs)});
        end
        $fclose(log);
        $finish;
    end
endmodule
"""


def main(argv):
    if len(argv) not in (3, 4) or argv[1] not in HARNESSES:
        print(__doc__)
        print("harnesses: " + " ".join(HARNESSES))
        return 2
    harness, out_dir = argv[1], argv[2]
    clocks = int(argv[3]) if len(argv) == 4 else 2000
    fmt, count, mx = HARNESSES[harness]
    rng = random.Random(20261019)
    ports = {}  # name -> (width, list of words)
    for _ in range(clocks):
        for name in ("a", "b"):
            word, width, scale = operand(rng, fmt, count, mx)
            ports.setdefault(name, (width, []))[1].append(word)
            if mx:
                ports.setdefault("scale_" + name, (8, []))[1].append(scale)
        c = (
            fp32_bits(rng.gauss(0, 4))
            if fmt != "int8"
            else round(rng.gauss(0, 4096)) & 0xFFFFFFFF
        )
        ports.setdefault("c", (32, []))[1].append(c)
    outputs = {"result": 32} if fmt == "int8" else {"result": 32, "exception_flags": 5}
    if harness == "ppa_fma_bf16":
        # Reset clears the valid pipeline during warm-up; every later clock carries a valid MAC.
        ports["rst"] = (1, [1, 1] + [0] * (clocks - 2))
        ports["in_valid"] = (1, [1] * clocks)
        outputs["out_valid"] = 1
    total = sum(width for width, _ in ports.values())
    with open(f"{out_dir}/stimulus.hex", "w") as out:
        for clock in range(clocks):
            word = 0
            for width, words in ports.values():
                word = word << width | words[clock]
            out.write(f"{word:0{(total + 3) // 4}x}\n")
    with open(f"{out_dir}/testbench.v", "w") as out:
        out.write(testbench(harness, out_dir, clocks, total, ports, outputs))
    print(
        f"wrote {out_dir}/testbench.v and stimulus.hex: {clocks} clocks, {total} input bits"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
