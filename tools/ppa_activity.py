"""Emit OpenSTA input activity for a PPA harness from realistic quantized operand streams.

Each clock carries independent N(0, 1) operands quantized to the harness format (OCP MX blocks
share a power-of-two scale); the accumulator input carries N(0, 16) FP32 values. For every input
pin the script measures the probability of a one (duty) and the per-clock toggle rate (activity).

usage: python3 tools/ppa_activity.py <harness> <out.tcl> [samples]
"""
import math
import random
import struct
import sys


def fp32_bits(x):
    return struct.unpack("<I", struct.pack("<f", x))[0]


def bf16(x):
    raw = fp32_bits(x)
    return ((raw + 0x7FFF + ((raw >> 16) & 1)) >> 16) & 0xFFFF


def small_float(x, exp_bits, man_bits, max_value):
    """Nearest-even encoding of x in a small sign/exponent/mantissa format, saturating."""
    sign = 1 if x < 0 else 0
    x = min(abs(x), max_value)
    bias = (1 << (exp_bits - 1)) - 1
    if x == 0:
        return sign << (exp_bits + man_bits)
    exponent = max(math.floor(math.log2(x)), 1 - bias)
    step = 2.0 ** (exponent - man_bits)
    q = round(x / step) * step
    if q >= 2.0 ** (exponent + 1):
        exponent += 1
    q = min(q, max_value)
    field = exponent + bias if q >= 2.0 ** (1 - bias) else 0
    frac = round(q / 2.0 ** ((field if field else 1) - bias - man_bits)) - (1 << man_bits if field else 0)
    return sign << (exp_bits + man_bits) | field << man_bits | int(frac)


FORMATS = {
    "bf16": (16, lambda x: bf16(x)),
    "e4m3": (8, lambda x: small_float(x, 4, 3, 448.0)),
    "e5m2": (8, lambda x: small_float(x, 5, 2, 57344.0)),
    "e2m1": (4, lambda x: small_float(x, 2, 1, 6.0)),
    "int8": (8, lambda x: max(-127, min(127, round(x * 32))) & 0xFF),
}
# Harness: element format, elements per operand, MX block (shared scale) or not, extra ports.
HARNESSES = {
    "ppa_fma_bf16": ("bf16", 1, False),
    "ppa_dot8_bf16": ("bf16", 8, False),
    "ppa_dot8_e4m3": ("e4m3", 8, False),
    "ppa_dot8_e5m2": ("e5m2", 8, False),
    "ppa_dot8_int8": ("int8", 8, False),
    "ppa_dot32_mxfp8": ("e4m3", 32, True),
    "ppa_dot32_mxfp4": ("e2m1", 32, True),
}
EMAX = {"e4m3": 8, "e2m1": 2}  # largest element exponent, per OCP MX scale selection


def operand(rng, fmt, count, mx):
    width, encode = FORMATS[fmt]
    values = [rng.gauss(0, 1) for _ in range(count)]
    scale = 0
    if mx:
        peak = max(abs(v) for v in values) or 1.0
        shared = math.floor(math.log2(peak)) - EMAX[fmt]
        scale = shared + 127
        values = [v / 2.0 ** shared for v in values]
    word = 0
    for k, v in enumerate(values):
        word |= encode(v) << (width * k)
    return word, width * count, scale


def main(argv):
    if len(argv) not in (3, 4) or argv[1] not in HARNESSES:
        print(__doc__)
        print("harnesses: " + " ".join(HARNESSES))
        return 2
    harness, out_path = argv[1], argv[2]
    samples = int(argv[3]) if len(argv) == 4 else 20000
    fmt, count, mx = HARNESSES[harness]
    rng = random.Random(20261019)
    ports = {}  # name -> (width, list of words)
    for _ in range(samples):
        for name in ("a", "b"):
            word, width, scale = operand(rng, fmt, count, mx)
            ports.setdefault(name, (width, []))[1].append(word)
            if mx:
                ports.setdefault("scale_" + name, (8, []))[1].append(scale)
        c = fp32_bits(rng.gauss(0, 4)) if fmt != "int8" else round(rng.gauss(0, 4096)) & 0xFFFFFFFF
        ports.setdefault("c", (32, []))[1].append(c)
    lines = ["# Generated by tools/ppa_activity.py " + harness]
    if harness == "ppa_fma_bf16":
        lines += ["set_power_activity -input_ports [get_ports in_valid] -activity 0 -duty 1",
                  "set_power_activity -input_ports [get_ports rst] -activity 0 -duty 0"]
    for name, (width, words) in ports.items():
        for bit in range(width):
            values = [(w >> bit) & 1 for w in words]
            duty = sum(values) / len(values)
            toggles = sum(x != y for x, y in zip(values, values[1:])) / (len(values) - 1)
            port = f"{name}[{bit}]" if width > 1 else name
            lines.append(f"set_power_activity -input_ports [get_ports {{{port}}}] -activity {toggles:.4f} -duty {duty:.4f}")
    with open(out_path, "w") as out:
        out.write("\n".join(lines) + "\n")
    print(f"wrote {out_path}: {len(lines) - 1} pin activities from {samples} clocks")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
